/// Parser para arquivos de bordado Viking / Pfaff (.vip)
///
/// Formato legado pré-VP3. Usa compressão ArchiveLib AL_GREENLEAF_LEVEL_4
/// e cores decodificadas por XOR com tabela fixa.
pub fn parse_vip(bytes: &[u8]) -> Result<EmbroideryPattern, String> {
    if bytes.len() < 0x2E {
        return Err("Arquivo VIP muito curto".to_string());
    }

    if !bytes.starts_with(&[0x5D, 0xFC, 0x90, 0x01]) && !bytes.starts_with(&[0x5B, 0xAF, 0x90, 0x01]) {
        return Err("Assinatura VIP inválida".to_string());
    }

    let stitch_count = u32::from_le_bytes([bytes[0x04], bytes[0x05], bytes[0x06], bytes[0x07]]) as usize;
    let color_count = u32::from_le_bytes([bytes[0x08], bytes[0x09], bytes[0x0A], bytes[0x0B]]) as usize;

    let offset_sec1 = u32::from_le_bytes([bytes[0x14], bytes[0x15], bytes[0x16], bytes[0x17]]) as usize;
    let offset_sec2 = u32::from_le_bytes([bytes[0x18], bytes[0x19], bytes[0x1A], bytes[0x1B]]) as usize;
    let offset_sec3 = u32::from_le_bytes([bytes[0x1C], bytes[0x1D], bytes[0x1E], bytes[0x1F]]) as usize;

    let mut pattern = EmbroideryPattern::new();

    let mut palette = Vec::new();
    let color_data_start = 0x2E;
    for i in 0..color_count {
        let base = color_data_start + i as usize * 4;
        if base + 3 < bytes.len() {
            let mut r = bytes[base];
            let mut g = bytes[base + 1];
            let mut b = bytes[base + 2];
            r = vip_xor_decode(r, base);
            g = vip_xor_decode(g, base + 1);
            b = vip_xor_decode(b, base + 2);
            palette.push(Rgba([r, g, b, 255]));
        }
    }

    if !palette.is_empty() {
        pattern.palette = Some(palette);
    }

    if stitch_count == 0 || offset_sec1 == 0 || offset_sec2 == 0 || offset_sec3 == 0 {
        return Ok(pattern);
    }

    parse_husky_sections(&mut pattern, bytes, stitch_count, offset_sec1, offset_sec2, offset_sec3, "VIP")?;

    Ok(pattern)
}

fn vip_xor_decode(value: u8, index: usize) -> u8 {
    let table_val = VIP_XOR_TABLE.get(index).copied().unwrap_or(0);
    value ^ table_val
}
